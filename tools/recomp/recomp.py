#!/usr/bin/env python3
"""Static recompiler driver: x86 PE -> C sources.

usage: recomp.py <exe> <outdir> [--ghidra functions.txt]
"""
import argparse
import os
import re
import sys

from image import Image
from analysis import discover_all
from codegen import FuncGen, liveness
from x87 import X87Gen
import overrides

FUNCS_PER_FILE = 120

PREAMBLE = '''/* Generated by tools/recomp — do not edit. */
#include "recomp.h"
#include "gen_decls.h"
#pragma GCC diagnostic ignored "-Wunused-label"
#pragma GCC diagnostic ignored "-Wunused-variable"
#pragma GCC diagnostic ignored "-Wunused-but-set-variable"
'''


class CodeGen:
    def __init__(self, img, an):
        self.img = img
        self.an = an
        self.x87 = X87Gen()
        self.errors = []
        self.used_imports = set()
        self.func_live_in = {}

    @staticmethod
    def fname(a):
        return f'f_{a:08x}'

    @staticmethod
    def impname(imp):
        dll, name = imp
        dll = dll.split('.')[0]
        return 'imp_' + re.sub(r'[^A-Za-z0-9_]', '_', f'{dll}_{name}')

    def exit_uses_fn(self, entry):
        funcs = self.an.funcs
        def uses(i):
            if i.kind in ('jmp', 'jcc') and i.target is not None and \
                    i.target in funcs and i.target != entry and i.target not in i.succ:
                return self.func_live_in.get(i.target, 0)
            return 0
        return uses

    def solve_liveness(self):
        self.live = {}
        for rnd in range(6):
            changed = False
            for e, insns in self.an.funcs.items():
                lo, li = liveness(insns, self.exit_uses_fn(e))
                self.live[e] = (lo, li)
                v = li[e]
                if self.func_live_in.get(e, 0) != v:
                    self.func_live_in[e] = v
                    changed = True
            if not changed:
                break
        n = sum(1 for v in self.func_live_in.values() if v)
        print(f'liveness: {rnd + 1} rounds, {n} functions with live-in flags')

    def gen_function(self, e):
        if e in overrides.OVERRIDES:
            return overrides.OVERRIDES[e](self.fname(e))
        lo, li = self.live[e]
        code = FuncGen(self, e, self.an.funcs[e], lo, li).generate()
        if e in overrides.WRAPS:
            # The recompiled body becomes <name>_orig; <name> calls the host
            # function, which gets the original to run or skip.
            name, host = self.fname(e), overrides.WRAPS[e]
            head = f'void {name}(CPU *restrict c) {{'
            assert code.startswith(head)
            code = (f'void {name}_orig(CPU *restrict c);\n'
                    f'void {host}(CPU *c, void (*orig)(CPU *restrict c));\n'
                    f'void {name}(CPU *restrict c) {{ {host}(c, {name}_orig); }}\n'
                    f'void {name}_orig(CPU *restrict c) {{' + code[len(head):])
        return code


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('exe')
    ap.add_argument('outdir')
    ap.add_argument('--ghidra')
    args = ap.parse_args()

    img = Image(args.exe)
    gh = []
    if args.ghidra:
        gh = [int(l.split()[0], 16) for l in open(args.ghidra)]
    an = discover_all(img, gh)
    print(f'{len(an.funcs)} functions, {sum(len(f) for f in an.funcs.values())} instructions')
    cg = CodeGen(img, an)
    cg.solve_liveness()

    os.makedirs(args.outdir, exist_ok=True)
    entries = sorted(an.funcs)
    with open(os.path.join(args.outdir, 'gen_decls.h'), 'w') as f:
        f.write('/* Generated by tools/recomp — do not edit. */\n#pragma once\n#include "recomp.h"\n')
        for e in entries:
            f.write(f'void {cg.fname(e)}(CPU *restrict c);\n')
        for iat, imp in sorted(img.imports.items()):
            f.write(f'void {cg.impname(imp)}(CPU *c);\n')

    files = []
    for k in range(0, len(entries), FUNCS_PER_FILE):
        chunk = entries[k:k + FUNCS_PER_FILE]
        name = f'gen_{k // FUNCS_PER_FILE:03d}.c'
        files.append(name)
        with open(os.path.join(args.outdir, name), 'w') as f:
            f.write(PREAMBLE)
            for e in chunk:
                f.write(cg.gen_function(e))
                f.write('\n')

    with open(os.path.join(args.outdir, 'gen_tables.c'), 'w') as f:
        f.write('/* Generated by tools/recomp — do not edit. */\n#include "recomp.h"\n#include "gen_decls.h"\n\n')
        f.write('const FuncEntry g_func_table[] = {\n')
        for e in entries:
            f.write(f'    {{0x{e:08x}u, {cg.fname(e)}}},\n')
        f.write('};\n')
        f.write(f'const uint32_t g_func_count = {len(entries)};\n\n')
        f.write('const ImportEntry g_import_table[] = {\n')
        for iat, (dll, name) in sorted(img.imports.items()):
            f.write(f'    {{0x{iat:08x}u, "{dll}", "{name}", {cg.impname((dll, name))}}},\n')
        f.write('};\n')
        f.write(f'const uint32_t g_import_count = {len(img.imports)};\n\n')
        f.write('/* Weak fallbacks: the runtime overrides the imports it implements. */\n')
        f.write('_Noreturn void unimplemented_import(CPU *c, const char *name);\n')
        for iat, (dll, name) in sorted(img.imports.items()):
            fn = cg.impname((dll, name))
            f.write(f'__attribute__((weak)) void {fn}(CPU *c) {{ unimplemented_import(c, "{dll}!{name}"); }}\n')

    # The image's headers and data sections, mapped by the runtime's pe_load,
    # so the built program needs no executable at run time.
    raw = open(args.exe, 'rb').read()
    with open(os.path.join(args.outdir, 'gen_image.c'), 'w') as f:
        f.write('/* Generated by tools/recomp — do not edit. */\n#include "recomp.h"\n\n')
        f.write(f'const uint32_t g_image_size = {len(raw)};\nconst uint8_t g_image[] = {{\n')
        for k in range(0, len(raw), 32):
            f.write(','.join(str(b) for b in raw[k:k + 32]) + ',\n')
        f.write('};\n')

    with open(os.path.join(args.outdir, 'gen_files.cmake'), 'w') as f:
        f.write('set(GEN_SOURCES\n' + ''.join(f'    ${{GEN_DIR}}/{n}\n' for n in files + ['gen_tables.c', 'gen_image.c']) + ')\n')

    with open(os.path.join(args.outdir, 'recomp_report.txt'), 'w') as f:
        f.write(f'functions {len(entries)}\n')
        f.write('noreturn ' + ' '.join(f'{x:08x}' for x in sorted(an.noreturn)) + '\n')
        f.write('\n'.join(an.warnings) + '\n')
        f.write('\n'.join(cg.errors) + '\n')
    print(f'{len(files)} source files, {len(cg.errors)} codegen errors, {len(an.warnings)} analysis warnings')
    for e in cg.errors[:40]:
        print('  ', e)


if __name__ == '__main__':
    main()
